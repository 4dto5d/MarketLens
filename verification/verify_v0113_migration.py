from __future__ import annotations

import hashlib
import json
import sqlite3
import sys
from contextlib import closing
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from local_presence_miner.database.engine import create_session_factory
from local_presence_miner.database.migrations import initialize_database


def rows(path: Path, sql: str):
    with closing(sqlite3.connect(path)) as connection:
        return connection.execute(sql).fetchall()


def main() -> int:
    database = Path(sys.argv[1]).resolve()
    report = Path(sys.argv[2]).resolve()
    if report.exists():
        raise RuntimeError(f"Refusing to overwrite report: {report}")
    before = {
        "lead": rows(database, "SELECT id,search_id,place_id,name,phone,website,status,notes,tags,owner FROM leads"),
        "search": rows(database, "SELECT id,name,city,state_region,niche,completed FROM lead_searches"),
        "draft": rows(database, "SELECT lead_id,kind,subject,body,approved,dependency_state FROM outreach_drafts"),
    }
    factory = create_session_factory(database)
    initialize_database(factory)
    backup = database.with_suffix(database.suffix + ".backup-before-v0113")
    first = {
        "lead": rows(database, "SELECT id,search_id,place_id,name,phone,website,status,notes,tags,owner FROM leads"),
        "notes": rows(database, "SELECT operator_notes,system_notes,notes_provenance FROM leads"),
        "search": rows(
            database,
            "SELECT id,name,city,state_region,niche,completed,lifecycle_state,total_candidates,succeeded_count FROM lead_searches",
        ),
        "membership": rows(
            database,
            "SELECT search_id,lead_id,candidate_place_id,candidate_name,discovery_kind,processing_status FROM search_run_leads",
        ),
        "lease_columns": rows(database, "PRAGMA table_info(search_run_leases)"),
        "draft": rows(database, "SELECT lead_id,kind,subject,body,approved,dependency_state FROM outreach_drafts"),
    }
    backup_hash = hashlib.sha256(backup.read_bytes()).hexdigest()
    initialize_database(factory)
    second_membership = rows(database, "SELECT search_id,lead_id,candidate_place_id,discovery_kind FROM search_run_leads")
    assertions = {
        "backup_exists_and_integrity_ok": backup.exists() and rows(backup, "PRAGMA integrity_check") == [("ok",)],
        "canonical_lead_fields_preserved": before["lead"] == first["lead"],
        "legacy_search_fields_preserved": before["search"] == [row[:6] for row in first["search"]],
        "approved_body_and_state_preserved": before["draft"] == first["draft"],
        "operator_note_copied_conservatively": first["notes"] == [
            ("Operator note created in immutable v0.1.12", "", "legacy_unknown")
        ],
        "legacy_membership_reconstructed_without_guessing": first["membership"] == [
            (1, 1, "immutable-v0112-place", "Immutable Fixture Roofing", "legacy_unknown", "Succeeded")
        ],
        "completed_run_lifecycle_and_counters": first["search"][0][6:] == ("Completed", 1, 1),
        "database_lease_schema_created": {
            row[1] for row in first["lease_columns"]
        } == {
            "lock_key",
            "owner_id",
            "owner_pid",
            "search_id",
            "acquired_at_epoch",
            "heartbeat_at_epoch",
            "expires_at_epoch",
        },
        "second_start_membership_idempotent": second_membership == [
            (1, 1, "immutable-v0112-place", "legacy_unknown")
        ],
        "backup_not_overwritten": hashlib.sha256(backup.read_bytes()).hexdigest() == backup_hash,
    }
    payload = {
        "fixture_origin": "Generated by the immutable extracted v0.1.12 source tree before v0.1.13 migration",
        "database": database.name,
        "backup": backup.name,
        "backup_sha256": backup_hash,
        "assertions": assertions,
        "status": "PASS" if all(assertions.values()) else "FAIL",
    }
    report.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    factory.kw["bind"].dispose()
    return 0 if payload["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
