from __future__ import annotations

import hashlib
import json
import sqlite3
import sys
from contextlib import closing
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parents[1]))

from local_presence_miner.database.engine import create_session_factory
from local_presence_miner.database.migrations import initialize_database


def rows(path: Path, sql: str):
    with closing(sqlite3.connect(path)) as connection:
        return connection.execute(sql).fetchall()


def main() -> int:
    database = Path(sys.argv[1]).resolve()
    report = Path(sys.argv[2]).resolve()
    if report.exists():
        raise RuntimeError(f"Refusing to overwrite report: {report}")
    before = {
        "lead": rows(
            database,
            "SELECT id,search_id,place_id,name,phone,website,status,operator_notes,"
            "system_notes,notes_provenance,notes,tags,owner FROM leads",
        ),
        "search": rows(
            database,
            "SELECT id,name,city,state_region,niche,completed,lifecycle_state,total_candidates,"
            "processed_count,succeeded_count,failed_count,new_count,rediscovered_count FROM lead_searches",
        ),
        "membership": rows(
            database,
            "SELECT search_id,lead_id,candidate_place_id,candidate_name,discovery_order,"
            "discovery_kind,processing_status FROM search_run_leads",
        ),
        "lease_table": rows(
            database,
            "SELECT name FROM sqlite_master WHERE type='table' AND name='search_run_leases'",
        ),
    }
    factory = create_session_factory(database)
    initialize_database(factory)
    backup = database.with_suffix(database.suffix + ".backup-before-v0113a")
    backup_hash = hashlib.sha256(backup.read_bytes()).hexdigest()
    current = {
        "lead": rows(
            database,
            "SELECT id,search_id,place_id,name,phone,website,status,operator_notes,"
            "system_notes,notes_provenance,notes,tags,owner FROM leads",
        ),
        "search": rows(
            database,
            "SELECT id,name,city,state_region,niche,completed,lifecycle_state,total_candidates,"
            "processed_count,succeeded_count,failed_count,new_count,rediscovered_count FROM lead_searches",
        ),
        "membership": rows(
            database,
            "SELECT search_id,lead_id,candidate_place_id,candidate_name,discovery_order,"
            "discovery_kind,processing_status FROM search_run_leads",
        ),
        "lease_columns": rows(database, "PRAGMA table_info(search_run_leases)"),
    }
    initialize_database(factory)
    assertions = {
        "immutable_fixture_was_pre_correction_v0113": before["lease_table"] == [],
        "backup_exists_and_integrity_ok": backup.exists()
        and rows(backup, "PRAGMA integrity_check") == [("ok",)],
        "backup_retains_pre_correction_schema": rows(
            backup,
            "SELECT name FROM sqlite_master WHERE type='table' AND name='search_run_leases'",
        )
        == [],
        "canonical_lead_fields_preserved": before["lead"] == current["lead"],
        "search_run_fields_preserved": before["search"] == current["search"],
        "membership_fields_preserved": before["membership"] == current["membership"],
        "database_lease_schema_created": {
            row[1] for row in current["lease_columns"]
        }
        == {
            "lock_key",
            "owner_id",
            "owner_pid",
            "search_id",
            "acquired_at_epoch",
            "heartbeat_at_epoch",
            "expires_at_epoch",
        },
        "backup_not_overwritten": hashlib.sha256(backup.read_bytes()).hexdigest()
        == backup_hash,
    }
    payload = {
        "fixture_origin": "Generated by immutable extracted v0.1.13 source ZIP before the v0.1.13a correction",
        "database": database.name,
        "backup": backup.name,
        "backup_sha256": backup_hash,
        "assertions": assertions,
        "status": "PASS" if all(assertions.values()) else "FAIL",
    }
    report.write_text(json.dumps(payload, indent=2), encoding="utf-8")
    factory.kw["bind"].dispose()
    return 0 if payload["status"] == "PASS" else 1


if __name__ == "__main__":
    raise SystemExit(main())
